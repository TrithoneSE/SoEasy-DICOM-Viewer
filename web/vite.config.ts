import { createHash } from "node:crypto";
import { createReadStream, existsSync, readdirSync, statSync } from "node:fs";
import { delimiter, join, relative, resolve, sep } from "node:path";
import { defineConfig, type Plugin } from "vite";

/** Content Security Policy of the built app: nothing may be fetched from, or sent to, another origin. */
const CSP = [
  "default-src 'self'",
  "script-src 'self' 'wasm-unsafe-eval'",
  "worker-src 'self'",
  "connect-src 'self'",
  "img-src 'self' data: blob:",
  "style-src 'self' 'unsafe-inline'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

function walk(dir: string): string[] {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

/** Builds sw.js with the list of every file of the build, so the installed app works offline. */
function serviceWorker(): Plugin {
  let publicDir = "";
  return {
    name: "soeasy-sw",
    apply: "build",
    configResolved(c) {
      publicDir = c.publicDir;
    },
    transformIndexHtml() {
      return [{ tag: "meta", attrs: { "http-equiv": "Content-Security-Policy", content: CSP }, injectTo: "head-prepend" }];
    },
    generateBundle(_, bundle) {
      const pub = existsSync(publicDir) ? walk(publicDir).map((p) => relative(publicDir, p).split(sep).join("/")) : [];
      const files = [...new Set(["./", ...Object.keys(bundle), ...pub])].filter((f) => f !== "sw.js").sort();
      const h = createHash("sha256");
      for (const f of files) {
        h.update(f);
        const out = bundle[f];
        if (out) h.update(out.type === "asset" ? out.source : out.code);
      }
      const version = h.digest("hex").slice(0, 12);
      const source = `// generated by vite.config.ts — offline cache of the app (never of patient data)
const CACHE = "soeasy-${version}";
const FILES = ${JSON.stringify(files)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("soeasy-") && k !== CACHE)
    .map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(req).catch(() =>
    req.mode === "navigate" ? caches.match("./") : Response.error())));
});
`;
      this.emitFile({ type: "asset", fileName: "sw.js", source });
    },
  };
}

/**
 * Dev only: serve local test data at /__testdata so the app can be driven without the file picker. DCV_TESTDATA
 * lists folders or files separated by ";" (Windows) / ":"; `?testdata=<n>/<subpath>` opens entry n. Bound to
 * localhost by Vite; the data never leave the machine.
 */
function testData(): Plugin {
  const roots = (process.env.DCV_TESTDATA ?? "").split(delimiter).filter(Boolean).map((r) => resolve(r));
  return {
    name: "soeasy-testdata",
    apply: "serve",
    configureServer(server) {
      if (!roots.length) return;
      server.middlewares.use("/__testdata", (req, res) => {
        const url = new URL(req.url ?? "/", "http://x");
        const [i, ...rest] = (url.searchParams.get("path") ?? "").split("/");
        const root = roots[Number(i)];
        const p = root && resolve(root, rest.join("/"));
        if (!p || !p.startsWith(root)) {
          res.statusCode = 403;
          res.end();
          return;
        }
        if (url.pathname === "/list") {
          const files = statSync(p).isDirectory() ? walk(p) : [p];
          res.setHeader("Content-Type", "application/json");
          res.end(JSON.stringify(files.map((f) => [i, ...relative(root, f).split(sep)].filter(Boolean).join("/"))));
        } else {
          res.setHeader("Content-Type", "application/octet-stream");
          createReadStream(p).pipe(res);
        }
      });
    },
  };
}

export default defineConfig({
  base: "./",
  plugins: [serviceWorker(), testData()],
  worker: { format: "es" },
  optimizeDeps: {
    include: [
      "dicom-parser",
      "jpeg-lossless-decoder-js",
      "@cornerstonejs/codec-charls/decodewasmjs",
      "@cornerstonejs/codec-openjpeg/decodewasmjs",
      "@cornerstonejs/codec-libjpeg-turbo-8bit/decodewasmjs",
    ],
  },
  server: {
    // cross-origin isolation in dev, so performance.measureUserAgentSpecificMemory() can report memory use
    headers: { "Cross-Origin-Opener-Policy": "same-origin", "Cross-Origin-Embedder-Policy": "require-corp" },
  },
  build: { target: "es2022", chunkSizeWarningLimit: 2000 },
  test: { environment: "node", include: ["tests/**/*.test.ts"] },
} as Parameters<typeof defineConfig>[0]);
